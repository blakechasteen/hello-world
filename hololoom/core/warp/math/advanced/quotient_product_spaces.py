class CoproductTopology:
    """Coproduct (disjoint union) of topological spaces.

    The disjoint union ⊔ Xᵢ has the coproduct topology where
    U ⊆ ⊔ Xᵢ is open iff U ∩ Xᵢ is open in Xᵢ for all i.
    Each component Xᵢ is both open and closed (clopen).

    Example:
        >>> X = TopologicalSpace.discrete(3)
        >>> Y = TopologicalSpace.discrete(2)
        >>> coprod = CoproductTopology([X, Y])
        >>> result = coprod.disjoint_union()
    """

    def __init__(self, spaces: list[TopologicalSpace]):
        """Initialize coproduct.

        Args:
            spaces: List of spaces to take disjoint union of.
        """
        self.spaces = spaces
        self.n_components = len(spaces)
        self._offsets: list[int] = []
        offset = 0
        for space in spaces:
            self._offsets.append(offset)
            offset += len(space.points)

    def disjoint_union(self) -> TopologicalSpace:
        """Compute the disjoint union topology.

        Points are re-indexed: space i's point j becomes offset_i + j.

        Returns:
            Disjoint union topological space.
        """
        all_points: set[int] = set()
        all_open: set[frozenset] = set()

        # Re-index points for each component
        point_maps: list[dict[int, int]] = []
        for i, space in enumerate(self.spaces):
            pmap = {}
            for p in space.points:
                new_idx = self._offsets[i] + p
                pmap[p] = new_idx
                all_points.add(new_idx)
            point_maps.append(pmap)

        # Generate open sets
        # Each combination of open sets from components is open
        component_opens = []
        for i, space in enumerate(self.spaces):
            translated = []
            for U in space.open_sets:
                translated.append(frozenset(point_maps[i][p] for p in U))
            component_opens.append(translated)

        # Build by unions of open sets from each component
        all_open.add(frozenset())
        current = [frozenset()]

        for i in range(self.n_components):
            new_sets = set()
            for existing in current:
                for U_i in component_opens[i]:
                    new_sets.add(existing | U_i)
            current = list(new_sets)
            all_open.update(new_sets)

        return TopologicalSpace(points=all_points, open_sets=all_open)

    def component_of(self, point: int) -> int:
        """Determine which component a point belongs to.

        Args:
            point: Point index in the disjoint union.

        Returns:
            Component index.
        """
        for i in range(self.n_components - 1, -1, -1):
            if point >= self._offsets[i]:
                return i
        return 0

    def inclusion(self, component: int, point: int) -> int:
        """Map a point from component space to disjoint union.

        Args:
            component: Component index.
            point: Point in component space.

        Returns:
            Point index in disjoint union.
        """
        return self._offsets[component] + point

    def fold_map(self, target: TopologicalSpace, maps: list[Callable[[int], int]]) -> Callable[[int], int]:
        """Universal property: maps from each component induce a map from coproduct.

        Given fᵢ: Xᵢ → Y for each i, there is a unique f: ⊔Xᵢ → Y.

        Args:
            target: Target space Y.
            maps: List of functions fᵢ: Xᵢ → Y.

        Returns:
            Combined function f: ⊔Xᵢ → Y.
        """
        offsets = self._offsets
        spaces = self.spaces

        def combined(point: int) -> int:
            comp = self.component_of(point)
            local_point = point - offsets[comp]
            return maps[comp](local_point)

        return combined
