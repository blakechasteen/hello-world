class ProductTopology:
    """Product of finitely many topological spaces.

    The product topology on Π Xᵢ is generated by sets of the form
    π_i⁻¹(U_i) = X₁ × ... × U_i × ... × Xₙ where U_i is open in Xᵢ.

    Example:
        >>> X = TopologicalSpace.discrete(3)
        >>> Y = TopologicalSpace.discrete(2)
        >>> prod = ProductTopology([X, Y])
        >>> prod.project((1, 0), 0)  # Project to first factor: 1
    """

    def __init__(self, spaces: list[TopologicalSpace]):
        """Initialize product topology.

        Args:
            spaces: List of factor spaces.
        """
        self.spaces = spaces
        self.n_factors = len(spaces)

    def project(self, point: tuple[int, ...], index: int) -> int:
        """Project product point to factor.

        Args:
            point: Point in product space (x₁, ..., xₙ).
            index: Factor index to project onto.

        Returns:
            Projected coordinate.
        """
        return point[index]

    def inject(self, value: int, index: int, base_point: tuple[int, ...] | None = None) -> tuple[int, ...]:
        """Inject into product at given factor.

        Creates a product point with the given value at the specified
        index and base_point values elsewhere.

        Args:
            value: Value to inject.
            index: Factor index.
            base_point: Values for other factors (defaults to min element).

        Returns:
            Point in product space.
        """
        if base_point is None:
            base_point = tuple(min(s.points) for s in self.spaces)

        result = list(base_point)
        result[index] = value
        return tuple(result)

    @property
    def product_points(self) -> set[tuple[int, ...]]:
        """All points in the product space."""
        if not self.spaces:
            return set()

        result = {(p,) for p in self.spaces[0].points}
        for space in self.spaces[1:]:
            new_result = set()
            for existing in result:
                for p in space.points:
                    new_result.add(existing + (p,))
            result = new_result

        return result

    def product_topology_space(self) -> TopologicalSpace:
        """Compute the product topological space explicitly.

        Warning: exponential in number of factors and points.
        Only practical for small spaces.

        Returns:
            Product topological space.
        """
        # Map product points to integer indices
        prod_points = sorted(self.product_points)
        point_to_idx = {p: i for i, p in enumerate(prod_points)}
        idx_points = set(range(len(prod_points)))

        # Generate basis: cylinder sets π_i⁻¹(U_i)
        basis: set[frozenset] = set()
        basis.add(frozenset())  # Empty set
        basis.add(frozenset(idx_points))  # Full set

        for i, space in enumerate(self.spaces):
            for U in space.open_sets:
                cylinder = frozenset(
                    point_to_idx[p] for p in prod_points
                    if p[i] in U
                )
                basis.add(cylinder)

        # Close under finite intersection and arbitrary union
        topology = set(basis)
        changed = True
        while changed:
            changed = False
            new_sets = set()
            topo_list = list(topology)
            for a in topo_list:
                for b in topo_list:
                    inter = a & b
                    union = a | b
                    if inter not in topology:
                        new_sets.add(inter)
                    if union not in topology:
                        new_sets.add(union)
            if new_sets:
                topology.update(new_sets)
                changed = True

        return TopologicalSpace(points=idx_points, open_sets=topology)

    def is_connected(self) -> bool:
        """Product is connected iff all factors are connected.

        A space is connected if it cannot be written as union of
        two disjoint non-empty open sets.
        """
        for space in self.spaces:
            if not self._is_space_connected(space):
                return False
        return True

    @staticmethod
    def _is_space_connected(space: TopologicalSpace) -> bool:
        """Check if a single space is connected."""
        for U in space.open_sets:
            if not U or U == frozenset(space.points):
                continue
            complement = frozenset(space.points) - U
            if complement in space.open_sets:
                return False
        return True


