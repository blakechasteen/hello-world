# DATA STRUCTURES
# ============================================================================

@dataclass
class TopologicalSpace:
    """Finite topological space represented by point set and open sets.

    Attributes:
        points: Set of point indices.
        open_sets: Collection of open sets (each a frozenset of point indices).
    """
    points: set[int]
    open_sets: set[frozenset]

    def is_open(self, subset: set[int]) -> bool:
        """Check if a subset is open."""
        return frozenset(subset) in self.open_sets

    def is_closed(self, subset: set[int]) -> bool:
        """Check if a subset is closed (complement is open)."""
        complement = self.points - subset
        return frozenset(complement) in self.open_sets

    @property
    def is_valid_topology(self) -> bool:
        """Verify topology axioms: empty and full set open, closed under union and finite intersection."""
        if frozenset() not in self.open_sets:
            return False
        if frozenset(self.points) not in self.open_sets:
            return False
        # Check pairwise intersections
        opens = list(self.open_sets)
        for i in range(len(opens)):
            for j in range(i + 1, len(opens)):
                if opens[i] & opens[j] not in self.open_sets:
                    return False
        # Check pairwise unions
        for i in range(len(opens)):
            for j in range(i + 1, len(opens)):
                if opens[i] | opens[j] not in self.open_sets:
                    return False
        return True

    @classmethod
    def discrete(cls, n: int) -> 'TopologicalSpace':
        """Create discrete topology (all subsets open)."""
        points = set(range(n))
        open_sets = set()
        # Generate all subsets
        for mask in range(2 ** n):
            subset = frozenset(i for i in range(n) if mask & (1 << i))
            open_sets.add(subset)
        return cls(points=points, open_sets=open_sets)

    @classmethod
    def indiscrete(cls, n: int) -> 'TopologicalSpace':
        """Create indiscrete topology (only empty and full set open)."""
        points = set(range(n))
        open_sets = {frozenset(), frozenset(points)}
        return cls(points=points, open_sets=open_sets)


