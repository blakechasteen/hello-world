# QUOTIENT SPACE
# ============================================================================

class QuotientSpace:
    """Quotient topological space X/~.

    Given a topological space X and an equivalence relation ~, the
    quotient space identifies equivalent points. The quotient topology
    is the finest topology making the projection π continuous.

    U ⊆ X/~ is open iff π⁻¹(U) is open in X.

    Example:
        >>> X = TopologicalSpace.discrete(4)
        >>> # Identify points 0≡1 and 2≡3
        >>> equiv = lambda a, b: a // 2 == b // 2
        >>> Q = QuotientSpace(X, equiv)
        >>> Q.project(0) == Q.project(1)  # True
    """

    def __init__(self, space: TopologicalSpace, equivalence: Callable[[int, int], bool]):
        """Initialize quotient space.

        Args:
            space: Base topological space X.
            equivalence: Equivalence relation (a, b) -> bool.
        """
        self.space = space
        self.equivalence = equivalence
        self._classes: dict[int, int] = {}  # point -> class representative
        self._compute_classes()

    def _compute_classes(self) -> None:
        """Compute equivalence classes using union-find."""
        parent: dict[int, int] = {p: p for p in self.space.points}

        def find(x: int) -> int:
            while parent[x] != x:
                parent[x] = parent[parent[x]]
                x = parent[x]
            return x

        def union(x: int, y: int) -> None:
            px, py = find(x), find(y)
            if px != py:
                parent[px] = py

        points = sorted(self.space.points)
        for i, a in enumerate(points):
            for b in points[i + 1:]:
                if self.equivalence(a, b):
                    union(a, b)

        self._classes = {p: find(p) for p in self.space.points}

    def project(self, point: int) -> int:
        """Project point to its equivalence class representative.

        Args:
            point: Point in X.

        Returns:
            Representative of [point] in X/~.
        """
        return self._classes.get(point, point)

    @property
    def quotient_points(self) -> set[int]:
        """Set of equivalence class representatives."""
        return set(self._classes.values())

    @property
    def equivalence_classes(self) -> dict[int, set[int]]:
        """Map from representative to equivalence class members."""
        classes: dict[int, set[int]] = {}
        for point, rep in self._classes.items():
            if rep not in classes:
                classes[rep] = set()
            classes[rep].add(point)
        return classes

    def quotient_topology(self) -> TopologicalSpace:
        """Compute the quotient topology.

        U ⊆ X/~ is open iff π⁻¹(U) is open in X.

        Returns:
            Quotient topological space.
        """
        q_points = self.quotient_points
        q_open: set[frozenset] = set()

        # Check all subsets of quotient points
        q_list = sorted(q_points)
        n = len(q_list)

        for mask in range(2 ** n):
            subset = frozenset(q_list[i] for i in range(n) if mask & (1 << i))
            # Compute preimage
            preimage = set()
            for point, rep in self._classes.items():
                if rep in subset:
                    preimage.add(point)
            # Check if preimage is open in X
            if frozenset(preimage) in self.space.open_sets:
                q_open.add(subset)

        return TopologicalSpace(points=q_points, open_sets=q_open)

    def is_hausdorff(self) -> bool:
        """Check if quotient space is Hausdorff (T2).

        A space is Hausdorff if distinct points have disjoint open
        neighborhoods.
        """
        qt = self.quotient_topology()
        q_points = sorted(qt.points)

        for i, p in enumerate(q_points):
            for q in q_points[i + 1:]:
                # Find disjoint open neighborhoods
                found = False
                for U in qt.open_sets:
                    if p not in U:
                        continue
                    for V in qt.open_sets:
                        if q not in V:
                            continue
                        if not (U & V):  # Disjoint
                            found = True
                            break
                    if found:
                        break
                if not found:
                    return False
        return True

    def lift_function(self, f: Callable[[int], Any]) -> Callable[[int], Any] | None:
        """Check if function f on X descends to quotient.

        f descends iff f(a) = f(b) whenever a ~ b.

        Args:
            f: Function on X.

        Returns:
            Descended function on X/~ if it exists, else None.
        """
        classes = self.equivalence_classes
        for rep, members in classes.items():
            values = {f(m) for m in members}
            if len(values) > 1:
                return None

        def descended(q_point: int) -> Any:
            return f(q_point)

        return descended


