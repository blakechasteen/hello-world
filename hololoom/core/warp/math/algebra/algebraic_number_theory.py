class RingOfIntegers:
    """
    Ring of integers O_K of a number field K.

    O_K = {α ∈ K : α is an algebraic integer}
        = {α ∈ K : the minimal polynomial of α has integer coefficients}

    For K = ℚ(√d):
        O_K = ℤ[√d]         if d ≡ 2, 3 (mod 4)
        O_K = ℤ[(1+√d)/2]   if d ≡ 1 (mod 4)
    """

    def __init__(self, field: NumberField):
        self.field = field
        self._integral_basis = self._compute_integral_basis()

    def _compute_integral_basis(self) -> list[np.ndarray]:
        """
        Compute an integral basis for O_K.

        Default: power basis {1, α, α², ..., α^{n-1}}.
        This equals O_K when the field discriminant equals
        the polynomial discriminant (monogenic case).
        """
        n = self.field.degree()
        basis = []
        for i in range(n):
            v = np.zeros(n)
            v[i] = 1.0
            basis.append(v)
        return basis

    def integral_basis(self) -> list[np.ndarray]:
        """Return the integral basis of O_K."""
        return [b.copy() for b in self._integral_basis]

    def is_element(self, alpha: np.ndarray) -> bool:
        """
        Check if α ∈ O_K by verifying its minimal polynomial has
        integer coefficients.
        """
        ai = AlgebraicInteger(alpha, self.field)
        min_poly = ai.minimal_polynomial()
        return all(abs(c - round(c)) < 1e-6 for c in min_poly)


