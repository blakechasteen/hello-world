class ClassGroup:
    """
    Ideal class group Cl(K) of a number field K.

    Cl(K) = (fractional ideals) / (principal ideals)
    h_K = |Cl(K)| is the class number.

    h_K = 1 ⟺ O_K is a PID (principal ideal domain)
           ⟺ O_K is a UFD (unique factorization domain)

    For imaginary quadratic fields ℚ(√-d), the class number
    can be computed via the Minkowski bound and quadratic forms.
    """

    def __init__(self, field: NumberField):
        self.field = field
        self._class_number = None
        self._representatives = None

    @staticmethod
    def compute(field: NumberField) -> 'ClassGroup':
        """Compute the class group of a number field."""
        cg = ClassGroup(field)
        cg._compute()
        return cg

    def _compute(self):
        """
        Compute class number using the Minkowski bound.

        Minkowski bound: every ideal class contains an ideal of norm ≤ M_K
        where M_K = (n!/nⁿ)(4/π)^{r₂} √|Δ_K|

        For small fields, enumerate ideals up to this bound.
        """
        n = self.field.degree()
        r1, r2 = self.field.signature()
        disc = abs(self.field.discriminant())

        if disc < 1e-10:
            self._class_number = 1
            return

        # Minkowski bound
        import math
        M = (math.factorial(n) / (n ** n)) * ((4 / np.pi) ** r2) * np.sqrt(disc)

        logger.info(f"Minkowski bound: {M:.2f}")

        # For quadratic fields, use the analytic formula
        if n == 2:
            self._class_number = self._quadratic_class_number()
        else:
            # General case: heuristic estimate
            # h ≈ √disc / (2π)^{r2} / R (where R is the regulator)
            self._class_number = max(1, int(round(np.sqrt(disc) / (2 * np.pi) ** r2)))

    def _quadratic_class_number(self) -> int:
        """
        Class number for quadratic fields ℚ(√d).

        For imaginary quadratic (d < 0): count reduced binary quadratic forms.
        For real quadratic (d > 0): use continued fraction for fundamental unit.
        """
        # Extract d from minimal polynomial x² - d
        d = -self.field.min_poly[0]  # min_poly = [-d, 0, 1]
        d = int(round(d))

        if d < 0:
            return self._imaginary_quadratic_class_number(d)
        else:
            return self._real_quadratic_class_number(d)

    def _imaginary_quadratic_class_number(self, d: int) -> int:
        """
        Class number of ℚ(√d) for d < 0.

        Count reduced binary quadratic forms of discriminant D.
        D = d if d ≡ 1 (mod 4), D = 4d otherwise.
        """
        if d % 4 == 1:
            D = d
        else:
            D = 4 * d

        D = abs(D)

        # Count reduced forms: |a| ≤ √(D/3), |b| ≤ a, a² ≤ D/3
        # Reduced form (a, b, c) with a > 0, |b| ≤ a, a ≤ c
        # and b ≥ 0 when a = c or |b| = a
        count = 0
        bound = int(np.sqrt(D / 3.0)) + 1

        for a in range(1, bound + 1):
            for b in range(-a, a + 1):
                # c = (b² + D) / (4a) for discriminant -D
                num = b * b + D
                if num % (4 * a) != 0:
                    continue
                c = num // (4 * a)

                if c < a:
                    continue

                # Reducedness conditions
                if abs(b) > a:
                    continue
                if a == c and b < 0:
                    continue
                if abs(b) == a and b < 0:
                    continue

                count += 1

        return max(1, count)

    def _real_quadratic_class_number(self, d: int) -> int:
        """
        Class number of ℚ(√d) for d > 0.

        Use the L-function approach: h = √D / (2 log ε) × L(1, χ_D)
        where ε is the fundamental unit and χ_D is the Kronecker symbol.
        Simplified: return 1 for small d (most common case).
        """
        # For many small d, h = 1
        # Full computation requires fundamental unit via continued fractions
        return 1

    def class_number(self) -> int:
        """Return the class number h_K."""
        if self._class_number is None:
            self._compute()
        return self._class_number

    def is_PID(self) -> bool:
        """O_K is a PID iff h_K = 1."""
        return self.class_number() == 1
