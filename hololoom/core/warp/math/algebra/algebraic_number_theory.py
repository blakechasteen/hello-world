class AlgebraicInteger:
    """
    An algebraic integer: root of a monic polynomial with integer coefficients.

    In a number field K = ℚ(α), algebraic integers form the ring O_K.
    Represented as a ℤ-linear combination of the integral basis.
    """

    def __init__(self, coefficients: np.ndarray, field: NumberField):
        """
        Args:
            coefficients: Integer coefficients in the power basis
                [a₀, a₁, ..., a_{n-1}] representing a₀ + a₁α + ... + a_{n-1}α^{n-1}.
            field: The ambient number field.
        """
        self.coeffs = np.array(coefficients, dtype=float)
        self.field = field

    def norm(self) -> float:
        """
        Norm N_{K/ℚ}(a) = Π σᵢ(a).

        For algebraic integers, the norm is always an integer.
        """
        return self.field.norm_element(self.coeffs)

    def trace(self) -> float:
        """
        Trace Tr_{K/ℚ}(a) = Σ σᵢ(a).

        For algebraic integers, the trace is always an integer.
        """
        return self.field.trace_element(self.coeffs)

    def minimal_polynomial(self) -> np.ndarray:
        """
        Compute the minimal polynomial of this algebraic integer over ℚ.

        The minimal polynomial divides the field's minimal polynomial.
        """
        n = self.field.degree()

        # Evaluate at all embeddings
        values = []
        for root in self.field.embeddings():
            val = sum(self.coeffs[i] * root ** i for i in range(len(self.coeffs)))
            values.append(val)

        # Build polynomial from these roots (some may be repeated)
        unique_vals = []
        for v in values:
            is_new = True
            for u in unique_vals:
                if abs(v - u) < 1e-8:
                    is_new = False
                    break
            if is_new:
                unique_vals.append(v)

        # Build minimal polynomial
        poly = np.array([1.0], dtype=complex)
        for root in unique_vals:
            poly = np.convolve(poly, np.array([1.0, -root]))

        # Round to integers
        result = np.real(poly[::-1])
        return np.round(result).astype(float)

    def __add__(self, other: 'AlgebraicInteger') -> 'AlgebraicInteger':
        return AlgebraicInteger(self.coeffs + other.coeffs, self.field)

    def __mul__(self, other: 'AlgebraicInteger') -> 'AlgebraicInteger':
        product = self.field.multiply_elements(self.coeffs, other.coeffs)
        return AlgebraicInteger(product, self.field)

    def __repr__(self):
        terms = []
        for i, c in enumerate(self.coeffs):
            if abs(c) < 1e-10:
                continue
            if i == 0:
                terms.append(f"{c:.0f}")
            elif i == 1:
                terms.append(f"{c:.0f}α")
            else:
                terms.append(f"{c:.0f}α^{i}")
        return " + ".join(terms) if terms else "0"


