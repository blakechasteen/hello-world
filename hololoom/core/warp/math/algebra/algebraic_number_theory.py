"""
Algebraic Number Theory for HoloLoom Warp Drive
=================================================

Number fields, algebraic integers, and class groups.

A number field K = ℚ(α) is a finite extension of the rationals,
generated by a root α of an irreducible polynomial f(x) ∈ ℚ[x].

Key objects:
- Ring of integers O_K: integral closure of ℤ in K
- Discriminant Δ_K: measures ramification of primes
- Class group Cl(K): measures failure of unique factorization
- Class number h_K = |Cl(K)|: h_K = 1 iff O_K is a PID (UFD)

Applications: cryptography, coding theory, Diophantine equations.

Author: HoloLoom Team
Date: 2026-03-19
"""

import logging

import numpy as np

logger = logging.getLogger(__name__)


# ============================================================================
# NUMBER FIELD
# ============================================================================

class NumberField:
    """
    Number field K = ℚ[x]/(f(x)) where f is irreducible over ℚ.

    Elements are polynomials in α (a root of f) of degree < deg(f).
    Arithmetic: polynomial arithmetic modulo f.
    """

    def __init__(self, min_poly: np.ndarray, name: str = "K"):
        """
        Args:
            min_poly: Coefficients of the minimal polynomial [a₀, a₁, ..., aₙ]
                      representing a₀ + a₁x + ... + aₙxⁿ. Must be monic (aₙ = 1).
            name: Field name.
        """
        self.min_poly = np.array(min_poly, dtype=float)
        self._degree = len(min_poly) - 1
        self.name = name

        # Normalize to monic
        if abs(self.min_poly[-1]) > 1e-14:
            self.min_poly = self.min_poly / self.min_poly[-1]

        # Compute roots (embeddings into ℂ)
        # np.roots expects highest degree first
        self._roots = np.roots(self.min_poly[::-1])

        logger.info(f"NumberField {name} = Q[x]/(f), degree={self._degree}")

    def degree(self) -> int:
        """[K : ℚ] = degree of the minimal polynomial."""
        return self._degree

    def embeddings(self) -> np.ndarray:
        """
        All embeddings σ: K → ℂ.

        Each root of the minimal polynomial gives an embedding.
        Returns array of complex roots.
        """
        return self._roots.copy()

    def signature(self) -> tuple[int, int]:
        """
        Signature (r₁, r₂) where:
        r₁ = number of real embeddings
        r₂ = number of pairs of complex conjugate embeddings
        n = r₁ + 2r₂
        """
        real_roots = sum(1 for r in self._roots if abs(r.imag) < 1e-10)
        complex_pairs = (self._degree - real_roots) // 2
        return real_roots, complex_pairs

    def discriminant(self) -> float:
        """
        Discriminant Δ_K = Π_{i<j} (αᵢ - αⱼ)².

        The discriminant measures how far O_K is from being ℤⁿ.
        Primes dividing Δ_K are exactly the ramified primes.
        """
        n = self._degree
        disc = 1.0
        for i in range(n):
            for j in range(i + 1, n):
                diff = self._roots[i] - self._roots[j]
                disc *= diff * diff

        # Should be rational (up to sign and leading coefficient)
        return float(np.real(disc))

    def ring_of_integers(self) -> 'RingOfIntegers':
        """
        Compute the ring of integers O_K.

        For quadratic fields Q(√d), O_K = ℤ[√d] if d ≡ 2, 3 (mod 4)
        and O_K = ℤ[(1+√d)/2] if d ≡ 1 (mod 4).

        For general fields, we return the power basis approximation
        O_K ≈ ℤ[α] (which equals O_K for monogenic fields).
        """
        return RingOfIntegers(self)

    def multiply_elements(self, a: np.ndarray, b: np.ndarray) -> np.ndarray:
        """
        Multiply two elements of K (given as polynomial coefficients mod f).

        a, b are arrays of length degree, representing
        a₀ + a₁α + ... + a_{n-1}α^{n-1}.
        """
        # Polynomial multiplication
        product = np.convolve(a, b)

        # Reduce modulo minimal polynomial
        return self._reduce(product)

    def _reduce(self, poly: np.ndarray) -> np.ndarray:
        """Reduce polynomial modulo the minimal polynomial."""
        n = self._degree
        result = poly.copy()

        while len(result) > n:
            if abs(result[-1]) < 1e-14:
                result = result[:-1]
                continue
            # Subtract leading_coeff * x^(deg-n) * min_poly
            lead = result[-1]
            deg = len(result) - 1
            shift = deg - n
            for i in range(n + 1):
                if shift + i < len(result):
                    result[shift + i] -= lead * self.min_poly[i]
            result = result[:max(n, len(result) - 1)]

        # Pad to length n
        if len(result) < n:
            result = np.concatenate([result, np.zeros(n - len(result))])

        return result[:n]

    def norm_element(self, a: np.ndarray) -> float:
        """
        Norm N_{K/ℚ}(a) = Π σᵢ(a) over all embeddings.
        """
        norm = 1.0
        for root in self._roots:
            # Evaluate a(root)
            val = sum(a[i] * root ** i for i in range(len(a)))
            norm *= val
        return float(np.real(norm))

    def trace_element(self, a: np.ndarray) -> float:
        """
        Trace Tr_{K/ℚ}(a) = Σ σᵢ(a) over all embeddings.
        """
        tr = 0.0
        for root in self._roots:
            val = sum(a[i] * root ** i for i in range(len(a)))
            tr += val
        return float(np.real(tr))

    @staticmethod
    def quadratic(d: int) -> 'NumberField':
        """
        Quadratic field ℚ(√d).

        Minimal polynomial: x² - d.
        """
        # Remove perfect square factors
        d_reduced = d
        for p in range(2, int(abs(d) ** 0.5) + 1):
            while d_reduced % (p * p) == 0:
                d_reduced //= (p * p)

        return NumberField(
            np.array([-d_reduced, 0, 1], dtype=float),
            name=f"Q(√{d_reduced})"
        )

    @staticmethod
    def cyclotomic(n: int) -> 'NumberField':
        """
        Cyclotomic field ℚ(ζₙ) where ζₙ = e^{2πi/n}.

        Minimal polynomial: n-th cyclotomic polynomial Φₙ(x).
        """
        # Compute cyclotomic polynomial via Möbius inversion
        coeffs = NumberField._cyclotomic_poly(n)
        return NumberField(coeffs, name=f"Q(ζ_{n})")

    @staticmethod
    def _cyclotomic_poly(n: int) -> np.ndarray:
        """Compute coefficients of the n-th cyclotomic polynomial."""
        # Start with x^n - 1, then divide by Φ_d for d | n, d < n
        # Simple implementation using roots of unity
        from math import gcd

        # Primitive n-th roots of unity
        roots = []
        for k in range(n):
            if gcd(k, n) == 1:
                roots.append(np.exp(2j * np.pi * k / n))

        # Build polynomial from roots
        poly = np.array([1.0], dtype=complex)
        for root in roots:
            poly = np.convolve(poly, np.array([1.0, -root]))

        # Should have integer (real) coefficients
        return np.real(poly[::-1])  # Reverse to get ascending order


